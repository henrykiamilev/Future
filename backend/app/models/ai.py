# --- API Response Models ---


class GeneratedItemResponse(BaseModel):
    """Single generated item in API response."""

    id: str
    type: AIItemType
    title: str
    scheduled_date: str | None
    scheduled_time: str | None
    end_time: str | None
    estimated_minutes: int | None
    is_flexible: bool
    purpose: str
    explanation: str
    category: str | None
    priority: AIPriority | None


class AIGenerateResponse(BaseModel):
    """Response from AI generation endpoint."""

    plan_id: str
    summary: str
    items: list[GeneratedItemResponse]
    events_created: int
    tasks_created: int
    tokens_remaining: int
